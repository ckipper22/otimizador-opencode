results = []
for i, (ean, desc, lab) in enumerate(items):
    body = json.dumps({
        "Token": token,
        "parametros": {"CnpjCLi": cnpj, "Ean": ean, "ConsideraTipo": 1}
    }).encode()

    try:
        req = urllib.request.Request("https://api.smartped.com.br/api/Condicoes/Molecula",
                                     data=body, headers={"Content-Type": "application/json"})
        resp = urllib.request.urlopen(req, timeout=15)
        data = json.loads(resp.read().decode())

        retorno = data.get("Retorno")
        if retorno is None:
            msg = data.get("Mensagem", "?")
            results.append((ean, desc, lab, "", "", msg))
            continue

        itens = retorno.get("itens") or retorno.get("Itens") or []
        if itens:
            entry = itens[0]
            mol = entry.get("Molecula", "")
            tipo = entry.get("TipoItem", "")
            subs = entry.get("Substitutos") or []
            suffix = mol.split("_")[-1] if mol and "_" in mol else ""

            results.append((ean, desc, lab, mol, tipo, suffix))
        else:
            results.append((ean, desc, lab, "", "", "sem itens"))

    except Exception as e:
        results.append((ean, desc, lab, "", "", f"ERRO: {e}"))

